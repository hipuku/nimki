/**
 * The live swatch check (master plan step 1.4c). The export is produced by a
 * script inside Figma, so a fault in that script would hide a difference from
 * every other check. This one reads the file another way: the Parity page holds
 * one swatch per colour variable per mode, each bound to its variable, and CI
 * reads what those swatches show through Figma's REST API.
 */
import { close, type Snapshot } from './figma.ts'

/** The page the swatches live on. */
export const SWATCH_PAGE = 'Parity'

/** The collection whose variables are colours. */
const COLLECTION = 'nimki/colour'

/** A node as Figma's REST API returns it, reduced to what the check reads. */
export interface RestNode {
  name: string
  type: string
  children?: RestNode[]
  fills?: {
    type: string
    opacity?: number
    color?: { r: number; g: number; b: number; a: number }
  }[]
}

/** Every colour variable, in code's order. */
function colourNames(expected: Snapshot): string[] {
  return Object.entries(expected.variables)
    .filter(([, v]) => v.collection === COLLECTION && v.type === 'COLOR')
    .map(([name]) => name)
}

/** A colour's value in a mode, following aliases to the colour they point at. */
function resolve(expected: Snapshot, name: string, mode: string): number[] | null {
  for (let seen = 0; seen < 10; seen++) {
    const value = expected.variables[name]?.values[mode]
    if (Array.isArray(value)) return value
    if (!value || typeof value !== 'object' || !('alias' in value)) return null
    name = value.alias as string
  }
  return null
}

/**
 * The script, for use_figma, that builds the Parity page: a frame per mode set
 * to that mode, holding a swatch for every colour variable. Running it again
 * rebuilds the page, so it follows variables being added or removed.
 */
export function swatchScript(expected: Snapshot): string {
  const names = colourNames(expected)
  const modes = expected.collections[COLLECTION] ?? []
  return `const names = ${JSON.stringify(names)};
const modes = ${JSON.stringify(modes)};
const collection = (await figma.variables.getLocalVariableCollectionsAsync()).find(c => c.name === ${JSON.stringify(COLLECTION)});
const vars = new Map((await figma.variables.getLocalVariablesAsync()).filter(v => v.variableCollectionId === collection.id).map(v => [v.name, v]));
const missing = names.filter(name => !vars.has(name));
if (missing.length > 0) return { error: 'Sync from code first; Figma has no ' + missing.join(', ') };
await figma.loadFontAsync({ family: 'Inter', style: 'Regular' });
const bind = (variable) => [figma.variables.setBoundVariableForPaint({ type: 'SOLID', color: { r: 0, g: 0, b: 0 } }, 'color', variable)];
let page = figma.root.children.find(p => p.name === ${JSON.stringify(SWATCH_PAGE)});
if (!page) { page = figma.createPage(); page.name = ${JSON.stringify(SWATCH_PAGE)}; }
for (const node of [...page.children]) node.remove();
const note = figma.createText();
page.appendChild(note);
note.fontSize = 14;
note.characters = 'Generated by pnpm figma:swatches --script. CI reads these swatches through Figma\\'s REST API and compares them with code (figma/README.md). Do not edit by hand; run the script again when a colour variable is added or removed.';
note.textAutoResize = 'HEIGHT';
note.resize(1000, note.height);
let y = note.height + 32;
for (const mode of modes) {
  const frame = figma.createFrame();
  page.appendChild(frame);
  frame.name = mode;
  frame.setExplicitVariableModeForCollection(collection, collection.modes.find(m => m.name === mode).modeId);
  frame.layoutMode = 'HORIZONTAL';
  frame.layoutWrap = 'WRAP';
  frame.primaryAxisSizingMode = 'FIXED';
  frame.counterAxisSizingMode = 'AUTO';
  frame.resize(1000, 100);
  frame.itemSpacing = 12;
  frame.counterAxisSpacing = 16;
  frame.paddingTop = frame.paddingBottom = frame.paddingLeft = frame.paddingRight = 24;
  frame.fills = bind(vars.get('background'));
  frame.y = y;
  for (const name of names) {
    const cell = figma.createFrame();
    frame.appendChild(cell);
    cell.name = name;
    cell.layoutMode = 'VERTICAL';
    cell.primaryAxisSizingMode = 'AUTO';
    cell.counterAxisSizingMode = 'FIXED';
    cell.resize(104, 10);
    cell.itemSpacing = 6;
    cell.fills = [];
    const swatch = figma.createRectangle();
    cell.appendChild(swatch);
    swatch.name = 'swatch';
    swatch.resize(104, 48);
    swatch.cornerRadius = 6;
    swatch.fills = bind(vars.get(name));
    swatch.strokes = bind(vars.get('border'));
    swatch.strokeWeight = 1;
    const label = figma.createText();
    cell.appendChild(label);
    label.fontSize = 10;
    label.characters = name;
    label.layoutSizingHorizontal = 'FILL';
    label.fills = bind(vars.get('foreground'));
  }
  y += frame.height + 40;
}
return { page: page.id, swatches: names.length * modes.length };`
}

/** What a swatch shows, as [r, g, b, a] like the snapshot's colours. */
function shown(cell: RestNode): number[] | null {
  const fill = cell.children?.find(child => child.name === 'swatch')?.fills?.[0]
  if (fill?.type !== 'SOLID' || !fill.color) return null
  const { r, g, b, a } = fill.color
  const round = (n: number) => Math.round(n * 1000) / 1000
  return [round(r), round(g), round(b), round(a * (fill.opacity ?? 1))]
}

/**
 * Compares the Parity page, as the REST API returns it, with code: every
 * colour variable needs a swatch in every mode showing code's value, and the
 * page holds no swatch for a variable code does not have.
 */
export function swatchProblems(expected: Snapshot, page: RestNode | undefined): string[] {
  const rebuild = 'run pnpm figma:swatches --script through use_figma to rebuild the page'
  if (!page) return [`The ${SWATCH_PAGE} page is missing: ${rebuild}`]
  const names = colourNames(expected)
  const problems: string[] = []
  for (const mode of expected.collections[COLLECTION] ?? []) {
    const frame = page.children?.find(child => child.name === mode && child.type === 'FRAME')
    if (!frame) {
      problems.push(`No ${mode} frame on the ${SWATCH_PAGE} page: ${rebuild}`)
      continue
    }
    const cells = new Map((frame.children ?? []).map(cell => [cell.name, cell]))
    for (const name of names) {
      const cell = cells.get(name)
      const want = resolve(expected, name, mode)
      if (!cell) {
        problems.push(`${name} (${mode}): no swatch; ${rebuild}`)
        continue
      }
      const got = shown(cell)
      if (!got) {
        problems.push(`${name} (${mode}): the swatch has no solid fill; ${rebuild}`)
      } else if (!want || !close(got, want)) {
        problems.push(
          `${name} (${mode}): Figma shows ${JSON.stringify(got)}, code has ${JSON.stringify(want)}`,
        )
      }
    }
    for (const name of cells.keys()) {
      if (!names.includes(name))
        problems.push(`${name} (${mode}): a swatch for a colour code does not have; ${rebuild}`)
    }
  }
  return problems
}
